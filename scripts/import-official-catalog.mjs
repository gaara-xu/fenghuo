// Only downloads public assets linked by the user-supplied Tencent catalog.
// No scripts from the source site are executed; existing artwork is preserved.
import { mkdir, writeFile, access } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
const root=fileURLToPath(new URL('..',import.meta.url))
const base='https://zg.qq.com/act/a20100623tbsq/'
const art=path.join(root,'public/art/official')
await mkdir(art,{recursive:true})
async function fetchBytes(url){const r=await fetch(url,{signal:AbortSignal.timeout(20000)});if(!r.ok)throw new Error(`${r.status}: ${url}`);return Buffer.from(await r.arrayBuffer())}
async function page(name){return new TextDecoder('gb18030').decode(await fetchBytes(base+name))}
async function asset(raw){const url=raw.replace(/^http:/,'https:');if(!url.startsWith('https://ossweb-img.qq.com/images/zg/act/a20100623tbsq/'))throw new Error('Unexpected image origin');const name=url.split('/').at(-1);const dest=path.join(art,name);try{await access(dest)}catch{const bytes=await fetchBytes(url);if(bytes.length<100)throw new Error('Empty image: '+url);await writeFile(dest,bytes)}return '/art/official/'+name}
const html=await page('suit_photo.htm'),heroHtml=await page('hero_intro.htm'),css=await page('css/style.css')
const sets=[],singles=[]
const clean=s=>s.replace(/<[^>]+>/g,'').replace(/&nbsp;/g,' ').trim()
for(const row of html.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)){
  const cells=[...row[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)].map(m=>m[1])
  const urls=[...(cells[0]??'').matchAll(/src="([^"]+trea_\d+\.jpg)"/g)].map(m=>m[1])
  if(urls.length===8){sets.push({name:clean(cells[2]),star:(cells[1].match(/star\.gif/g)??[]).length,icons:[]});for(const u of urls)sets.at(-1).icons.push(await asset(u))}
}
for(const cell of html.matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)){
 const urls=[...cell[1].matchAll(/src="([^"]+trea_\d+\.jpg)"/g)].map(m=>m[1])
 if(urls.length===1)singles.push({name:clean(cell[1]),star:(cell[1].match(/star\.gif/g)??[]).length,icon:await asset(urls[0])})
}
const heroes=[...heroHtml.matchAll(/<h5[^>]*>([^<]+)<\/h5>/g)].map(m=>({name:m[1].replace(/★/g,'').trim(),star:(m[1].match(/★/g)??[]).length}))
const sprite=css.match(/#hero_intro\{[^}]+url\(([^)]+)\)/)?.[1]
if(!sprite||heroes.length!==26||sets.length!==15||singles.length!==45)throw new Error(`Unexpected source catalog: ${heroes.length}/${sets.length}/${singles.length}`)
await asset(sprite)
for(const name of ['suit_attribute','suit_concise','suit_mosaic','hero_suit'])await asset(`https://ossweb-img.qq.com/images/zg/act/a20100623tbsq/photo/${name}.jpg`)
const catalog={source:base+'suit_photo.htm',heroSource:base+'hero_intro.htm',heroes,sets,singles}
await writeFile(path.join(root,'shared/official-catalog-data.ts'),'// Generated by scripts/import-official-catalog.mjs from the official catalog.\nexport const officialCatalog = '+JSON.stringify(catalog,null,2)+' as const\n')
console.log(`Imported ${heroes.length} hero entries, ${sets.length*8+singles.length} equipment icons.`)
